import { Pool as PgPool } from 'pg';
import { Pool as NeonPool } from '@neondatabase/serverless';
import { sha256 } from '@/lib/jwt';

const connectionString = process.env.DATABASE_URL || 'postgres://postgres:postgres@localhost:5432/agua_db';

// Detecta si se debe usar el driver de Neon (por variable de entorno, URL o entorno Vercel)
const isNeon =
  process.env.NEON === 'true' ||
  process.env.USE_NEON === 'true' ||
  connectionString.includes('neon.tech') ||
  Boolean(process.env.VERCEL && process.env.DATABASE_URL);

const rawPool = isNeon
  ? new NeonPool({ connectionString })
  : new PgPool({
      connectionString,
      connectionTimeoutMillis: 5000,
      idleTimeoutMillis: 30000,
    });

// Pool universal compatible con Neon Serverless (@neondatabase/serverless) y pg local
export const pool = {
  async query<R = any>(text: string, values?: any[]): Promise<{ rows: R[]; rowCount?: number | null }> {
    return (rawPool as any).query(text, values);
  },
  async connect() {
    return (rawPool as any).connect();
  },
};

let isSchemaInitialized = false;

// Comprobación de estado de conexión a PostgreSQL
export async function testConnection(): Promise<boolean> {
  try {
    const client = await pool.connect();
    client.release();
    if (!isSchemaInitialized) {
      await initDatabaseSchema();
      isSchemaInitialized = true;
    }
    return true;
  } catch (error) {
    console.error('Error al conectar con PostgreSQL:', error);
    return false;
  }
}

// Inicialización de tablas DDL en PostgreSQL si no existen
export async function initDatabaseSchema() {
  const ddl = `
    CREATE TABLE IF NOT EXISTS "Localidad" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "nombre" VARCHAR(255),
      "cp" VARCHAR(10),
      "provincia" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Cooperativa" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idLocalidad" INTEGER NOT NULL,
      "nombre" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Pozo" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idCooperativa" INTEGER NOT NULL,
      "coordX" VARCHAR(50),
      "coordY" VARCHAR(50),
      "profundidadPozo" DECIMAL(18,2),
      "profundidadBomba" DECIMAL,
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Medidor" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idCooperativa" INTEGER,
      "marca" VARCHAR(255),
      "modelo" VARCHAR(255),
      "nroSerie" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Mantenimiento" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idMedidor" INTEGER,
      "fecha" DATE,
      "detalle" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Magnitudes" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "nombre" VARCHAR(255),
      "abreviatura" VARCHAR(255),
      "valorMax" VARCHAR(255),
      "valorMin" VARCHAR(255),
      "unidad" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Medicion" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idMedidor" INTEGER,
      "idPozo" INTEGER,
      "idMagnitud" INTEGER,
      "medicion" DECIMAL,
      "fecha" TIMESTAMP,
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Usuario" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "email" VARCHAR(255) UNIQUE,
      "password_hash" VARCHAR(255),
      "nombre" VARCHAR(255),
      PRIMARY KEY("id")
    );

    ALTER TABLE "Usuario" ADD COLUMN IF NOT EXISTS "email" VARCHAR(255);
    ALTER TABLE "Usuario" ADD COLUMN IF NOT EXISTS "password_hash" VARCHAR(255);
    ALTER TABLE "Usuario" ADD COLUMN IF NOT EXISTS "nombre" VARCHAR(255);
  `;
  try {
    await pool.query(ddl);

    // Insertar usuario administrador por defecto si no existe aún
    const userCheck = await pool.query(
      'SELECT id FROM "Usuario" WHERE LOWER("email") = $1 OR LOWER("nombre") = $2 LIMIT 1',
      ['admin@aguametrics.com', 'admin']
    );
    if (userCheck.rows.length === 0) {
      const defaultEmail = 'admin@aguametrics.com';
      const defaultPassword = 'admin';
      const hash = await sha256(defaultPassword);
      await pool.query(
        'INSERT INTO "Usuario" ("email", "password_hash", "nombre") VALUES ($1, $2, $3)',
        [defaultEmail, hash, 'admin']
      );
      console.log('Usuario administrador por defecto creado exitosamente:', defaultEmail);
    }
  } catch (err) {
    console.error('Error al inicializar esquema PostgreSQL:', err);
  }
}