// Variable para tracking de conexión
let isPgConnected: boolean | null = null;

export async function testConnection(): Promise<boolean> {
  if (isPgConnected !== null) return isPgConnected;
  if (!process.env.DATABASE_URL) {
    isPgConnected = false;
    return false;
  }
  try {
    const client = await pool.connect();
    client.release();
    isPgConnected = true;
    return true;
  } catch {
    isPgConnected = false;
    return false;
  }
}

// SQL DDL Initialization
export async function initDatabaseSchema() {
  const connected = await testConnection();
  if (!connected) return;

  const ddl = `
    CREATE TABLE IF NOT EXISTS "Localidad" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "nombre" VARCHAR(255),
      "cp" VARCHAR(10),
      "provincia" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Cooperativa" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idLocalidad" INTEGER NOT NULL,
      "nombre" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Pozo" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idCooperativa" INTEGER NOT NULL,
      "coordX" VARCHAR(50),
      "coordY" VARCHAR(50),
      "profundidadPozo" DECIMAL(18,2),
      "profundidadBomba" DECIMAL,
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Medidor" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idCooperativa" INTEGER,
      "marca" VARCHAR(255),
      "modelo" VARCHAR(255),
      "nroSerie" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Mantenimiento" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idMedidor" INTEGER,
      "fecha" DATE,
      "detalle" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Magnitudes" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "nombre" VARCHAR(255),
      "abreviatura" VARCHAR(255),
      "valorMax" VARCHAR(255),
      "valorMin" VARCHAR(255),
      "unidad" VARCHAR(255),
      PRIMARY KEY("id")
    );

    CREATE TABLE IF NOT EXISTS "Medicion" (
      "id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
      "idMedidor" INTEGER,
      "idPozo" INTEGER,
      "idMagnitud" INTEGER,
      "medicion" DECIMAL,
      "fecha" TIMESTAMP,
      PRIMARY KEY("id")
    );
  `;
  try {
    await pool.query(ddl);
  } catch (err) {
    console.error('Error al inicializar esquema PostgreSQL:', err);
  }
}

